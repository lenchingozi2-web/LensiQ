Definition: Satellitism is a laboratory phenomenon in which colonies of Haemophilu
influenzae grow larger in the immediate vicinity of colonies of Staphylococcus aureu
(or other organisms) streaked on the same blood agar plate, with colony siz
diminishing with increasing distance from the S. aureus streak.
