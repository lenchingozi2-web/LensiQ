Principle and procedure of Gram staining
Principle: Gram staining is a differential staining technique that exploits difference
in bacterial cell wall structure. Gram-positive bacteria have a thick peptidoglycan laye
that retains the crystal violet-iodine complex despite decolourisation with
alcohol/acetone, staining purple. Gram-negative bacteria have a thin peptidoglycan
layer and an outer lipopolysaccharide membrane that is disrupted by the decolouriser
releasing the crystal violet-iodine complex; they then take up the counterstain
(safranin), staining pink/red.
Procedure: 1. Fixation: prepare a thin smear of the specimen on a glass slide, air-dry
and heat-fix by passing through a flame. 2. Primary stain: flood the smear with crysta
violet for 30–60 seconds; rinse with water. 3. Mordant: apply Gram’s iodine for 30–6
seconds (forms crystal violet-iodine complex within the cell wall); rinse with water. 4
Decolourisation: apply acetone/alcohol briefly (a few seconds) until no more purpl
colour washes off; rinse immediately with water — this is the critical differentiating
step. 5. Counterstain: apply safranin for 30–60 seconds; rinse with water. 6. Dry and
examine under oil-immersion microscopy (×100).
Interpretation: Gram-positive organisms appear purple/blue; Gram-negativ
organisms appear pink/red. Morphology (cocci, bacilli, arrangement) is also noted.
