required for cytochrome synthesis) and Factor V (NAD, required for oxidation
reduction reactions) — which are not readily available on unheated blood (sheep) aga
because Factor V is inactivated by an NADase in sheep red blood cells, and th
bacteria cannot lyse the intact red cells to release Factor X. Staphylococcus aureu
growing on the same plate haemolyses red blood cells (releasing Factor X) and, mor
importantly, secretes Factor V (NAD) into the surrounding medium, thereby “feeding
the nearby H. influenzae colonies and allowing them to grow — hence “satellite
colonies clustering around the staphylococcal streak. On chocolate agar (heated blood
agar), both factors are already freely available, so satellitism is not seen, and H
influenzae grows uniformly.

