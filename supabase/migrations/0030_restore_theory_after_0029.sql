Koch’s postulates and their limitations
Koch’s postulates (criteria to establish a causal link between a microorganism and
disease): 1. The organism must be found in abundance in all organisms suffering from
the disease, but not in healthy individuals. 2. The organism must be isolated from
diseased host and grown in pure culture. 3. The cultured organism should caus
disease when introduced into a healthy, susceptible host. 4. The organism must be re
isolated from the experimentally infected host and identified as identical to the origina
causative agent.
Limitations: - Some pathogens cannot be cultured in vitro (e.g., Mycobacterium
leprae, Treponema pallidum). - Some organisms cause disease only in specific hosts
making animal models unsuitable (host specificity). - Asymptomatic carriers exist —
the organism may be present without causing disease. - Some diseases have multipl
causative agents (polymicrobial infections), violating postulate 1. - Some agents caus
several different disease presentations (e.g., Streptococcus pyogenes). - Ethica
constraints prevent deliberate infection of human volunteers for many pathogens.
Viruses require living cells (not simple culture media) for propagation, which wa
unknown in Koch’s era. - Latent/slow viral infections (e.g., prions, some herpesviruses
may not fulfil the postulates temporally.
